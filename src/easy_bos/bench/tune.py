"""Parameter sweeps used to choose each method's defaults from the benchmark.

``uv run python -m easy_bos.bench.tune`` renders the tuning scenarios once, runs each method over
a small grid of its main parameters through the production pipeline, and writes
``docs/tuning.md``. The score is the mean over scenarios of EPE divided by that scenario's best
EPE across all runs, so every scenario counts equally whatever its displacement scale.
"""

from __future__ import annotations

import itertools
from pathlib import Path

import numpy as np

from easy_bos.bench import suite
from easy_bos.core.media import ArraySource
from easy_bos.core.pipeline import ProcessingSettings, Processor

SCENARIOS = ["plume-raw", "plume-h264", "turbulent", "plate", "lens", "breath"]

GRIDS: dict[str, dict[str, list]] = {
    "variational": {
        "alpha": [0.3, 1.0, 3.0, 10.0, 30.0],
        "regularizer": ["first", "second"],
        "curl_weight": [0.0, 10.0],
    },
    "wavelet": {"lam": [1.0, 3.0, 10.0, 30.0, 100.0]},
    "correlation": {"window": [12, 16, 24, 32], "overlap": [0.75]},
    "lucas_kanade": {"window_sigma": [1.5, 2.0, 3.0, 4.0]},
    "farneback": {"window": [9, 15, 21, 31]},
}


def _combos(grid: dict[str, list]) -> list[dict]:
    keys = list(grid)
    return [dict(zip(keys, vals, strict=True)) for vals in itertools.product(*grid.values())]


def run(methods: list[str] | None = None, size=(512, 384), log=print) -> list[dict]:
    captures = {}
    for sc in suite.scenarios():
        if sc.key in SCENARIOS:
            captures[sc.key] = (sc, suite.render_scenario(sc, size))
    rows = []
    for method, grid in GRIDS.items():
        if methods and method not in methods:
            continue
        for params in _combos(grid):
            row = {"method": method, "params": params, "epe": {}}
            for key, (sc, (_setup, _scene, cap)) in captures.items():
                settings = ProcessingSettings(
                    method=method,
                    method_params=params,
                    reference_range=(0, sc.n_ref),
                    **sc.settings,
                )
                proc = Processor(ArraySource(cap.frames), settings)
                idx = cap.flow_frames[0]
                res = proc.process_frame(idx)
                row["epe"][key] = suite.score(res.displacement, cap.truth[idx])["epe"]
            rows.append(row)
            scores = "  ".join(f"{k} {v:.4f}" for k, v in row["epe"].items())
            log(f"{method:13s} {params}  {scores}")
    best = {k: min(r["epe"][k] for r in rows) for k in captures}
    for r in rows:
        r["score"] = float(np.mean([r["epe"][k] / best[k] for k in captures]))
    return rows


def write(rows: list[dict], path: Path) -> None:
    lines = [
        "# Parameter tuning",
        "",
        "Generated by `uv run python -m easy_bos.bench.tune`. Score = mean over scenarios of "
        "EPE / best EPE for that scenario (1.0 = best everywhere). Scenarios: "
        + ", ".join(f"`{s}`" for s in SCENARIOS)
        + ".",
        "",
    ]
    for method in GRIDS:
        mr = sorted((r for r in rows if r["method"] == method), key=lambda r: r["score"])
        if not mr:
            continue
        lines += [
            f"## {method}",
            "",
            "| Parameters | Score | " + " | ".join(SCENARIOS) + " |",
            "|---|---:|" + "---:|" * len(SCENARIOS),
        ]
        for r in mr:
            p = ", ".join(f"{k}={v}" for k, v in r["params"].items())
            lines.append(
                f"| {p} | {r['score']:.2f} | "
                + " | ".join(f"{r['epe'][s]:.4f}" for s in SCENARIOS)
                + " |"
            )
        lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    import sys

    out = run(sys.argv[1:] or None)
    write(out, Path("docs/tuning.md"))
